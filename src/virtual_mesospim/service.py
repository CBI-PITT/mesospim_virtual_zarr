"""Multi-dataset HTTP service for the micro_status Flask web app.

Serves read-only virtual stitched mosaics for any dataset whose mosaic.json
manifest is managed by the web app, plus a local Neuroglancer client, from one
long-running process. Dataset manifests are discovered on demand from signed,
expiring access tokens generated by the web app; nothing is written to tile
stores or manifests. This replaces starting one ``mesospim-virtual-zarr``
command per dataset with a single shared service.
"""
