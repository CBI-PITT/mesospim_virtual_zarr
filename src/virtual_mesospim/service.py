from .engine import VirtualMosaic


_RANGE = re.compile(r"^bytes=(\d*)-(\d*)$")


class MosaicLoadError(RuntimeError):
    """A dataset mosaic.json manifest could not be loaded."""


def sign_token(secret: str, dataset_id: int, path: str, max_age: int) -> str:
    """Expiring access token for one dataset directory.

    Format: base64url(dataset_id|expiry|path).hex_hmac_sha256. The web app
    signs with its secret key; this service verifies with the same secret.
    """
    expiry = int(time.time()) + max_age
    payload = f"{dataset_id}|{expiry}|{path}"
    signature = hmac.new(secret.encode("utf-8"), payload.encode("utf-8"),
                         hashlib.sha256).hexdigest()
    return f"{base64.urlsafe_b64encode(payload.encode('utf-8')).decode('ascii')}.{signature}"


def verify_token(token: str, secret: str, dataset_id: int) -> str | None:
    """Return the signed dataset directory path, or None if the token is
    invalid, expired, or belongs to a different dataset."""
    try:
        encoded, signature = token.split(".", 1)
        payload = base64.urlsafe_b64decode(encoded.encode("ascii")).decode("utf-8")
        expected = hmac.new(secret.encode("utf-8"), payload.encode("utf-8"),
                            hashlib.sha256).hexdigest()
        if not hmac.compare_digest(signature, expected):
            return None
        signed_id, expiry, path = payload.split("|", 2)
        if int(signed_id) != int(dataset_id) or time.time() > int(expiry):
            return None
        if not path or not Path(path).is_absolute():
            return None
        return path
    except (ValueError, UnicodeError):
        return None


def default_client_dir() -> Path | None:
    """Prebuilt Neuroglancer client shipped with the neuroglancer package."""
    try:
        import neuroglancer
    except ImportError:
        return None
    client = Path(neuroglancer.__file__).parent / "static" / "client"
    return client if (client / "index.html").is_file() else None


@dataclass
class _LoadedMosaic:
    mosaic: VirtualMosaic
    semaphore: asyncio.Semaphore
    window: tuple[float, float] | None = None


def _display_window_sampled(mosaic: VirtualMosaic, max_chunks: int = 8,
                            sample_step: int = 4) -> tuple[float, float] | None:
    """Normalized contrast window from the coarsest level, compositing at
    most max_chunks chunks.

    A full scan (small coarsest level) gives an exact window; for large
    coarsest levels a strided chunk sample still bounds the wait for the first
    viewer open. Each chunk composite reads its intersecting source tiles, so
    bounding the chunk count bounds the wait for the first viewer open."""
    try:
        index = len(mosaic.levels) - 1
        level = mosaic.levels[index]
        ranges = [range(-(-size // chunk)) for size, chunk in zip(level.shape, level.chunk_shape)]
        total_chunks = 1
        for axis_range in ranges:
            total_chunks *= len(axis_range)
        stride = max(1, -(-total_chunks // max_chunks))
        patches = {}
        for count, coords in enumerate(itertools.product(*ranges)):
            if count % stride:
                continue
            chunk = mosaic.compose_chunk(index, coords)
            start = tuple(c * ch for c, ch in zip(coords, level.chunk_shape))
            stop = tuple(min(a + b, n) for a, b, n in zip(start, level.chunk_shape, level.shape))
            patches[coords] = chunk[tuple(slice(a, b) for a, b in zip(start, stop))]
        values = np.concatenate([patch.ravel()[::sample_step] for patch in patches.values()])
        nonzero = values[values > 0]
        if nonzero.size < 0.01 * values.size:
            return None
        low, high = np.percentile(nonzero, (1, 99))
        if np.isfinite(low) and np.isfinite(high) and high > low:
            return float(low), float(high)
        return None
    except Exception:
        return None


def _viewer_state(entries: list[_LoadedMosaic], data_base: str) -> dict:
    """Viewer state for the local client: one image layer per channel.
    data_base must be an absolute URL that already carries the per-dataset
    access token in its path (Neuroglancer cannot parse relative source URLs,
    and the client corrupts query-string tokens when it appends chunk keys to
    the namespace URL)."""
    first = entries[0].mosaic
    level = first.levels[0]
    names = first.axis_names[-3:]
    scale_um = level.scale[-3:]
    shape = level.shape[-3:]
    layers = []
    opacity = 0.7 if len(entries) > 1 else 1
    for entry in entries:
        mosaic = entry.mosaic
        base = f"{data_base}/{mosaic.config.channel}" if mosaic.config.channel else data_base
        layer = {"type": "image", "name": mosaic.config.name,
                 "source": f"{base}/|zarr3:", "opacity": opacity}
        if mosaic.config.color:
            layer["shader"] = _color_shader(color_to_rgb(mosaic.config.color))
        if entry.window is not None:
            layer["shaderControls"] = {"normalized": {"range": list(entry.window)}}
        layers.append(layer)
    # Open on the middle z/y/x plane of the volume. The viewer position in the
    # URL-fragment state is in voxel coordinates of the display dimensions
    # (level-0 voxels here), not physical units.
    position = [size / 2 for size in shape]
    # Single-panel, zoomed-out view: fit the whole dataset within a small
    # fraction of the panel so it opens quickly at a coarse pyramid level.
    # Neuroglancer renders one canonical voxel (the smallest displayed voxel
    # size) per viewport pixel at crossSectionScale = 1, so the fitted scale
    # is the largest visible extent in canonical voxels over the target size.
    target_pixels = 200
    visible = list(zip(shape[-2:], scale_um[-2:]))
    canonical_voxel_um = min(s for _, s in visible)
    cross_section_scale = (max(size * s for size, s in visible)
                           / (target_pixels * canonical_voxel_um))
    return {
        "dimensions": {name: [s * 1e-6, "m"] for name, s in zip(names, scale_um)},
        "position": position,
        "crossSectionScale": cross_section_scale,
        "layers": layers,
        "selectedLayer": {"layer": layers[0]["name"]},
        "layout": "xy",
    }


async def _serve_key(mosaic: VirtualMosaic, limiter: asyncio.Semaphore,
                     key: str, request: Request) -> Response:
    if not mosaic.has_key(key):
        raise HTTPException(status_code=404, detail="No such virtual Zarr key")
    try:
        async with limiter:
            content = await run_in_threadpool(mosaic.get_bytes, key)
    except Exception as exc:
        # Unexpected I/O/codec exceptions should not become 404s.
        raise HTTPException(status_code=500, detail="Source tile read or compositing failed") from exc
    if content is None:
        raise HTTPException(status_code=404, detail="No such virtual Zarr key")
    size = len(content)
    headers = {"Accept-Ranges": "bytes", "Cache-Control": "no-store"}
    status = 200
    range_header = request.headers.get("range")
    if range_header:
        match = _RANGE.fullmatch(range_header)
        if match is None:
            raise HTTPException(status_code=416, detail="Only a single bytes=start-end range is supported",
                                headers={"Content-Range": f"bytes */{size}"})
        if not match.group(1) and not match.group(2):
            raise HTTPException(status_code=416, detail="Empty byte range",
                                headers={"Content-Range": f"bytes */{size}"})
        if match.group(1):
            start = int(match.group(1))
            stop = min(int(match.group(2)) + 1, size) if match.group(2) else size
        else:
            # Suffix form: bytes=-N
            start = max(0, size - int(match.group(2)))
            stop = size
        if start >= size or start >= stop:
            raise HTTPException(status_code=416, detail="Range not satisfiable",
                                headers={"Content-Range": f"bytes */{size}"})
        content = content[start:stop]
        headers["Content-Range"] = f"bytes {start}-{stop-1}/{size}"
        status = 206
    media_type = "application/json" if key.endswith("zarr.json") else "application/octet-stream"
    return Response(content=b"" if request.method == "HEAD" else content,
                    status_code=status, media_type=media_type,
                    headers={**headers, "Content-Length": str(len(content))})


def create_service_app(token_secret: str, client_dir: Path | None = None,
                       max_datasets: int = 4) -> FastAPI:
    """Service app: token-protected virtual Zarr keys per dataset, a viewer
    launch route that redirects to the local Neuroglancer client, and the
    client itself served from the same origin (no CORS needed).

    Tokens bind one dataset id to one absolute manifest directory and expire;
    without a valid token no dataset file is even read.
    """
    cache: OrderedDict[str, tuple[tuple, list[_LoadedMosaic]]] = OrderedDict()
    cache_lock = threading.Lock()

    def get_or_load(path: str) -> list[_LoadedMosaic]:
        """Bounded in-memory cache of loaded mosaics, invalidated when the
        manifest or the auto-discovered gain.json changes on disk."""
        manifest = Path(path) / "mosaic.json"
        if not manifest.is_file():
            raise MosaicLoadError(f"No mosaic.json manifest in {path}")
        gain = Path(path) / "gain.json"
        manifest_stat = manifest.stat()
        stamp = (manifest_stat.st_mtime_ns, manifest_stat.st_size,
                 gain.stat().st_mtime_ns if gain.is_file() else 0)
        with cache_lock:
            cached = cache.get(path)
            if cached and cached[0] == stamp:
                cache.move_to_end(path)
                return cached[1]
        configs = load_mosaic_configs(manifest)
        entries = [_LoadedMosaic(VirtualMosaic(config),
                                 asyncio.Semaphore(config.max_concurrent_chunks))
                   for config in configs]
        with cache_lock:
            cache[path] = (stamp, entries)
            cache.move_to_end(path)
            while len(cache) > max_datasets:
                cache.popitem(last=False)
        return entries

    app = FastAPI(title="Virtual MesoSPIM dataset service", docs_url=None, redoc_url=None)
    if client_dir is not None:
        # The bundled client is the python-integration build: at page load it
        # parses the URL path for a /v/<token>/ segment and crashes with
        # "Failed to determine token from URL." otherwise. It must be served
        # under a /v/.../ prefix (as neuroglancer's own StaticFileServer does).
        app.mount("/v/viewer", StaticFiles(directory=str(client_dir), html=True),
                  name="neuroglancer")

    @app.get("/healthz")
    def healthz():
        with cache_lock:
            return {"status": "ok", "datasets": list(cache.keys())}

    def require_dataset(request: Request, dataset_id: int) -> str:
        path = verify_token(request.query_params.get("token", ""), token_secret, dataset_id)
        if path is None:
            raise HTTPException(status_code=403, detail="Invalid or expired dataset token")
        return path

    @app.get("/datasets/{dataset_id}/viewer")
    def dataset_viewer(dataset_id: int, request: Request):
        token = request.query_params.get("token", "")
        path = require_dataset(request, dataset_id)
        try:
            entries = get_or_load(path)
        except (MosaicLoadError, ValueError, OSError) as exc:
            raise HTTPException(status_code=500,
                                detail=f"Could not load virtual mosaic: {exc}") from exc
        # Compute once per loaded mosaic; subsequent opens reuse the window.
        for entry in entries:
            if entry.window is None:
                entry.window = _display_window_sampled(entry.mosaic)
        # The token rides in the path: Neuroglancer appends chunk keys directly
        # to the namespace URL, which corrupts query-string tokens.
        data_base = (f"{str(request.base_url).rstrip('/')}"
                     f"/t/{token}/datasets/{dataset_id}/{entries[0].mosaic.config.mount_path}")
        state = _viewer_state(entries, data_base)
        url = f"/v/viewer/index.html#!{quote(json.dumps(state, separators=(',', ':')), safe='')}"
        return RedirectResponse(url, status_code=302)

    # Registered after /viewer so the viewer route matches first.
    @app.api_route("/datasets/{dataset_id}/{rest:path}", methods=["GET", "HEAD"])
    async def dataset_zarr_key(dataset_id: int, rest: str, request: Request):
        return await _serve_dataset_entries(require_dataset(request, dataset_id), rest, request)

    # Path-token namespace: /t/<token>/datasets/<id>/<mount>[/<channel>]/<key>.
    @app.api_route("/t/{token}/{rest:path}", methods=["GET", "HEAD"])
    async def dataset_zarr_key_path(token: str, rest: str, request: Request):
        parts = rest.split("/", 2)
        if len(parts) < 2 or parts[0] != "datasets" or not parts[1].isdigit():
            raise HTTPException(status_code=404, detail="No such virtual Zarr namespace")
        dataset_id = int(parts[1])
        path = verify_token(token, token_secret, dataset_id)
        if path is None:
            raise HTTPException(status_code=403, detail="Invalid or expired dataset token")
        return await _serve_dataset_entries(
            path, parts[2] if len(parts) > 2 else "", request)

    async def _serve_dataset_entries(path: str, rest: str, request: Request) -> Response:
        try:
            entries = await run_in_threadpool(get_or_load, path)
        except (MosaicLoadError, ValueError, OSError) as exc:
            raise HTTPException(status_code=500,
                                detail=f"Could not load virtual mosaic: {exc}") from exc
        segments = rest.split("/")
        mounted = [entry for entry in entries if entry.mosaic.config.mount_path == segments[0]]
        if not mounted:
            raise HTTPException(status_code=404, detail="No such virtual Zarr namespace")
        loaded = mounted[0]
        remainder = segments[1:]
        if loaded.mosaic.config.channel is not None or len(entries) > 1:
            if not remainder:
                raise HTTPException(status_code=404, detail="Channel path required")
            channel, key = remainder[0], "/".join(remainder[1:])
            by_channel = [entry for entry in entries if entry.mosaic.config.channel == channel]
            if not by_channel:
                raise HTTPException(status_code=404, detail="No such channel")
            loaded = by_channel[0]
        else:
            key = "/".join(remainder)
        return await _serve_key(loaded.mosaic, loaded.semaphore, key, request)

    return app


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(
        description="Serve read-only virtual stitched MesoSPIM mosaics for every "
                    "dataset managed by the micro_status web app, plus a local "
                    "Neuroglancer client")
    parser.add_argument("--host", default="0.0.0.0",
                        help="Bind address (default: 0.0.0.0; LAN use behind the web app's tokens)")
    parser.add_argument("--port", type=int, default=1415)
    parser.add_argument("--token-secret", required=True,
                        help="Shared secret; must equal the web app's Flask secret key "
                             "used to sign dataset tokens")
    parser.add_argument("--client-dir", default=None,
                        help="Neuroglancer static client directory "
                             "(default: the one bundled with the neuroglancer package)")
    parser.add_argument("--max-datasets", type=int, default=4,
                        help="Datasets kept loaded in memory (default: 4)")
    args = parser.parse_args(argv)

    client = Path(args.client_dir) if args.client_dir else default_client_dir()
    if client is None or not (client / "index.html").is_file():
        print("Warning: no Neuroglancer client found; install the neuroglancer package "
              "into this environment or pass --client-dir. Zarr keys still serve, "
              "but /datasets/<id>/viewer will fail.")
    import uvicorn

    app = create_service_app(args.token_secret, client, args.max_datasets)
    print(f"Virtual dataset service: http://{args.host}:{args.port}/  "
          f"(Neuroglancer client: {client if client else 'not found'})")
    print("Dataset tokens must be signed with the same secret as the web app "
          "(--token-secret).")
    uvicorn.run(app, host=args.host, port=args.port, workers=1)


if __name__ == "__main__":
    main()
